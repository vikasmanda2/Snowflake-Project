FROM BRONZE_RAW_CLAIMS;

--Final Reconciliation Query


WITH BRONZE_TOTAL AS
(
    SELECT
        SUM(PAYLOAD:billed_amount::NUMBER(18,2))
        AS BRONZE_GROSS_TOTAL
    FROM BRONZE_RAW_CLAIMS
),

SILVER_TOTAL AS
(
    SELECT
        SUM(BILLED_AMOUNT)
        AS SILVER_GROSS_TOTAL
    FROM SILVER_CLAIMS_TRANSACTIONS
),

GOLD_TOTAL AS
(
    SELECT
        SUM(TOTAL_BILLED_AMOUNT)
        AS GOLD_GROSS_TOTAL
    FROM DT_PROVIDER_FINANCIAL_SUMMARY
)

SELECT
    BRONZE_GROSS_TOTAL,
    SILVER_GROSS_TOTAL,
    GOLD_GROSS_TOTAL,

    CASE
        WHEN BRONZE_GROSS_TOTAL = 257700.00
         AND SILVER_GROSS_TOTAL = 197700.00
         AND GOLD_GROSS_TOTAL = 152700.00
        THEN TRUE
        ELSE FALSE
    END AS RECONCILED_FLAG

FROM BRONZE_TOTAL
CROSS JOIN SILVER_TOTAL
CROSS JOIN GOLD_TOTAL;

