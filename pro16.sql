-- CREATING THE SILVER LAYER
CREATE OR REPLACE TABLE SILVER_CLAIMS_TRANSACTIONS
(
    CLAIM_ID STRING,
    SUBMITTED_AT TIMESTAMP_TZ,
    PATIENT_ID NUMBER,
    PROVIDER_ID STRING,
    DIAGNOSIS_CODE STRING,
    BILLED_AMOUNT NUMBER(18,2),
    COPAY_AMOUNT NUMBER(18,2),
    NET_PAYABLE_AMOUNT NUMBER(18,2),
    STATUS STRING
);


MERGE INTO SILVER_CLAIMS_TRANSACTIONS AS TARGET

USING
(
    SELECT
        PAYLOAD:claim_id::STRING AS CLAIM_ID,
        PAYLOAD:submitted_at::TIMESTAMP_TZ AS SUBMITTED_AT,
        PAYLOAD:patient_id::NUMBER AS PATIENT_ID,
        PAYLOAD:provider_id::STRING AS PROVIDER_ID,
        PAYLOAD:diagnosis_code::STRING AS DIAGNOSIS_CODE,
        PAYLOAD:billed_amount::NUMBER(18,2) AS BILLED_AMOUNT,
        PAYLOAD:copay_amount::NUMBER(18,2) AS COPAY_AMOUNT,
        (
            PAYLOAD:billed_amount::NUMBER(18,2)
            -
            PAYLOAD:copay_amount::NUMBER(18,2)
        ) AS NET_PAYABLE_AMOUNT,
        PAYLOAD:status::STRING AS STATUS
    FROM
    (
        SELECT
            *,
            ROW_NUMBER() OVER
            (
                PARTITION BY PAYLOAD:claim_id::STRING
                ORDER BY INGEST_ID DESC
            ) AS RN
        FROM STRM_BRONZE_CLAIMS
        WHERE METADATA$ACTION = 'INSERT'
    )
    WHERE RN = 1
) AS SOURCE

ON TARGET.CLAIM_ID = SOURCE.CLAIM_ID

WHEN MATCHED THEN UPDATE SET
    TARGET.SUBMITTED_AT = SOURCE.SUBMITTED_AT,
    TARGET.PATIENT_ID = SOURCE.PATIENT_ID,
    TARGET.PROVIDER_ID = SOURCE.PROVIDER_ID,
    TARGET.DIAGNOSIS_CODE = SOURCE.DIAGNOSIS_CODE,
    TARGET.BILLED_AMOUNT = SOURCE.BILLED_AMOUNT,
    TARGET.COPAY_AMOUNT = SOURCE.COPAY_AMOUNT,
    TARGET.NET_PAYABLE_AMOUNT = SOURCE.NET_PAYABLE_AMOUNT,
    TARGET.STATUS = SOURCE.STATUS

WHEN NOT MATCHED THEN INSERT
(
    CLAIM_ID,
    SUBMITTED_AT,
    PATIENT_ID,
    PROVIDER_ID,
    DIAGNOSIS_CODE,
    BILLED_AMOUNT,
    COPAY_AMOUNT,
    NET_PAYABLE_AMOUNT,
    STATUS
)
VALUES
(
    SOURCE.CLAIM_ID,
    SOURCE.SUBMITTED_AT,
    SOURCE.PATIENT_ID,
    SOURCE.PROVIDER_ID,
    SOURCE.DIAGNOSIS_CODE,
    SOURCE.BILLED_AMOUNT,
    SOURCE.COPAY_AMOUNT,
    SOURCE.NET_PAYABLE_AMOUNT,
    SOURCE.STATUS
);


SELECT
    CLAIM_ID,
    PATIENT_ID,
    PROVIDER_ID,
    DIAGNOSIS_CODE,
    BILLED_AMOUNT,
    COPAY_AMOUNT,
    NET_PAYABLE_AMOUNT,
    STATUS
FROM SILVER_CLAIMS_TRANSACTIONS
ORDER BY CLAIM_ID;

--TASK 4 — Dynamic Table
CREATE OR REPLACE DYNAMIC TABLE DT_PROVIDER_FINANCIAL_SUMMARY
(
    PROVIDER_ID,
    TOTAL_BILLED_AMOUNT,
    TOTAL_COPAY_COLLECT,
    TOTAL_NET_PAYABLE,
    APPROVED_CLAIMS
)
TARGET_LAG = '1 minute'
WAREHOUSE = COMPUTE_WH
REFRESH_MODE = INCREMENTAL
AS
SELECT
    PROVIDER_ID,
    SUM(BILLED_AMOUNT) AS TOTAL_BILLED_AMOUNT,
    SUM(COPAY_AMOUNT) AS TOTAL_COPAY_COLLECT,
    SUM(NET_PAYABLE_AMOUNT) AS TOTAL_NET_PAYABLE,
    COUNT(*) AS APPROVED_CLAIMS
FROM SILVER_CLAIMS_TRANSACTIONS
WHERE STATUS = 'APPROVED'
GROUP BY PROVIDER_ID;

SELECT
    PROVIDER_ID,
    TOTAL_BILLED_AMOUNT,
    TOTAL_COPAY_COLLECT,
    TOTAL_NET_PAYABLE,
    APPROVED_CLAIMS
FROM DT_PROVIDER_FINANCIAL_SUMMARY
ORDER BY PROVIDER_ID;


---TASK 5 — Dynamic Table Refresh Monitoring

SELECT
    NAME AS DYNAMIC_TABLE_NAME,
    REFRESH_ACTION,
    CASE
        WHEN REFRESH_ACTION = 'INCREMENTAL'
            THEN 'INCREMENTAL'
        WHEN REFRESH_ACTION = 'FULL'
            THEN 'FULL'
        ELSE REFRESH_ACTION
    END AS REFRESH_MODE,
    CASE
        WHEN STATE = 'SUCCEEDED'
            THEN 'SUCCESS'
        ELSE STATE
    END AS QUALIFIED_STATUS,
    REFRESH_TRIGGER,
    REFRESH_START_TIME,
    REFRESH_END_TIME
FROM TABLE
(
    INFORMATION_SCHEMA.DYNAMIC_TABLE_REFRESH_HISTORY
    (
        NAME => 'HEALTHCARE_PIPELINE_DB.CLAIMS_CORE.DT_PROVIDER_FINANCIAL_SUMMARY',
        RESULT_LIMIT => 100
    )
)
ORDER BY REFRESH_START_TIME DESC;

