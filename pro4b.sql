--END-TO-END RECONCILIATION
--Bronze Gross Total
SELECT
    SUM(RAW_PAYLOAD:amount::NUMBER(14,2)) AS BRONZE_GROSS_SUM
FROM BRONZE_PAYMENT_PAYLOADS;


----SILVER  Gross Total
SELECT
    SUM(GROSS_AMOUNT) AS SILVER_GROSS_SUM
FROM SILVER_CLEANED_TRANSACTIONS;

--GOLD GROSS TOTAL
SELECT
    SUM(TOTAL_APPROVED_GROSS) AS GOLD_GROSS_SUM
FROM GOLD_MERCHANT_SETTLEMENTS;


--Final Reconciliation Query
WITH RECONCILIATION AS (

    SELECT
        (
            SELECT SUM(
                RAW_PAYLOAD:amount::NUMBER(14,2)
            )
            FROM BRONZE_PAYMENT_PAYLOADS
        ) AS BRONZE_GROSS_SUM,

        (
            SELECT SUM(GROSS_AMOUNT)
            FROM SILVER_CLEANED_TRANSACTIONS
        ) AS SILVER_GROSS_SUM,

        (
            SELECT SUM(TOTAL_APPROVED_GROSS)
            FROM GOLD_MERCHANT_SETTLEMENTS
        ) AS GOLD_GROSS_SUM
)

SELECT
    BRONZE_GROSS_SUM,
    SILVER_GROSS_SUM,
    GOLD_GROSS_SUM,

    CASE
        WHEN BRONZE_GROSS_SUM = SILVER_GROSS_SUM
        THEN TRUE
        ELSE FALSE
    END AS DATA_MATCH_FLAG

FROM RECONCILIATION;
