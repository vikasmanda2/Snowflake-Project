-- SILVER TABLE 
CREATE OR REPLACE TABLE SILVER_CLEANED_TRANSACTIONS (
    TXN_ID VARCHAR,
    TXN_TIME TIMESTAMP_TZ,
    MERCHANT_ID NUMBER,
    MERCHANT_NAME VARCHAR,

    MASKED_CARD VARCHAR,

    GROSS_AMOUNT NUMBER(14,2),
    FEE_PCT NUMBER(5,2),

    PROCESSING_FEE NUMBER(14,2),
    NET_SETTLEMENT_AMOUNT NUMBER(14,2),

    STATUS VARCHAR,

    SILVER_CREATED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()
);

INSERT INTO SILVER_CLEANED_TRANSACTIONS (
    TXN_ID,
    TXN_TIME,
    MERCHANT_ID,
    MERCHANT_NAME,
    MASKED_CARD,
    GROSS_AMOUNT,
    FEE_PCT,
    PROCESSING_FEE,
    NET_SETTLEMENT_AMOUNT,
    STATUS
)
SELECT
    RAW_PAYLOAD:txn_id::VARCHAR AS TXN_ID,

    RAW_PAYLOAD:txn_time::TIMESTAMP_TZ AS TXN_TIME,

    RAW_PAYLOAD:merchant_id::NUMBER AS MERCHANT_ID,

    RAW_PAYLOAD:merchant_name::VARCHAR AS MERCHANT_NAME,

    'XXXX-XXXX-XXXX-' ||
    RIGHT(
        RAW_PAYLOAD:card_number::VARCHAR,
        4
    ) AS MASKED_CARD,

    RAW_PAYLOAD:amount::NUMBER(14,2) AS GROSS_AMOUNT,

    RAW_PAYLOAD:fee_pct::NUMBER(5,2) AS FEE_PCT,

    ROUND(
        RAW_PAYLOAD:amount::NUMBER(14,2)
        *
        (
            RAW_PAYLOAD:fee_pct::NUMBER(5,2) / 100
        ),
        2
    ) AS PROCESSING_FEE,

    ROUND(
        RAW_PAYLOAD:amount::NUMBER(14,2)
        -
        (
            RAW_PAYLOAD:amount::NUMBER(14,2)
            *
            (
                RAW_PAYLOAD:fee_pct::NUMBER(5,2) / 100
            )
        ),
        2
    ) AS NET_SETTLEMENT_AMOUNT,

    RAW_PAYLOAD:status::VARCHAR AS STATUS

FROM BRONZE_PAYMENT_PAYLOADS;


SELECT
    TXN_ID,
    MERCHANT_ID,
    MERCHANT_NAME,
    MASKED_CARD,
    GROSS_AMOUNT AS GROSS,
    PROCESSING_FEE,
    NET_SETTLEMENT_AMOUNT,
    STATUS
FROM SILVER_CLEANED_TRANSACTIONS
ORDER BY TXN_ID;

