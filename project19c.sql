 --TASK 6 BUSINESS ANALYSIS:


SELECT
    f.SENDER_ACC AS ACCOUNT_ID,

    COUNT(*) AS HIGH_RISK_TXN_COUNT,

    'NEVER_AUDITED' AS COMPLIANCE_STATUS

FROM FACT_WIRE_TRANSFERS f

INNER JOIN DIM_WIRE_ATTRIBUTES d
    ON f.ATTRIBUTE_SK = d.ATTRIBUTE_SK

LEFT JOIN FACTLESS_COMPLIANCE_AUDIT_COVERAGE a
    ON f.SENDER_ACC = a.ACCOUNT_ID
   AND a.AUDIT_YEAR = 2026

WHERE d.RISK_FLAG = 'HIGH'
  AND a.ACCOUNT_ID IS NULL

GROUP BY f.SENDER_ACC

ORDER BY f.SENDER_ACC;



 --TASK 7: RISK PROFILE CROSS-ANALYSIS

SELECT
    d.RISK_FLAG,
    d.TRANSFER_TYPE,

    COUNT(*) AS TOTAL_TXNS,

    SUM(f.FEE) AS TOTAL_FEES,

    SUM(f.BASE_AMOUNT_USD) AS TOTAL_VOLUME_USD

FROM FACT_WIRE_TRANSFERS f

INNER JOIN DIM_WIRE_ATTRIBUTES d
    ON f.ATTRIBUTE_SK = d.ATTRIBUTE_SK

GROUP BY
    d.RISK_FLAG,
    d.TRANSFER_TYPE

ORDER BY
    d.RISK_FLAG,
    d.TRANSFER_TYPE;


 --TASK 8: MULTI-FACT RECONCILIATION

WITH WIRE_TOTAL AS
(
    SELECT
        SUM(BASE_AMOUNT_USD) AS TOTAL_WIRE_VOL_USD
    FROM FACT_WIRE_TRANSFERS
),

LATEST_VAULT AS
(
    SELECT
        SUM(CLOSING_BALANCE) AS VAULT_CLOSING_USD

    FROM FACT_VAULT_CASH_SNAPSHOT

    WHERE SNAPSHOT_DATE =
    (
        SELECT MAX(SNAPSHOT_DATE)
        FROM FACT_VAULT_CASH_SNAPSHOT
    )
),

COMPLETED_LOANS AS
(
    SELECT
        COUNT(*) AS COMPLETED_LOAN_APPS

    FROM FACT_CREDIT_APPROVAL_LIFECYCLE

    WHERE DISBURSEMENT_DATE IS NOT NULL
)

SELECT
    w.TOTAL_WIRE_VOL_USD,

    v.VAULT_CLOSING_USD,

    l.COMPLETED_LOAN_APPS,

    CASE

        WHEN w.TOTAL_WIRE_VOL_USD = 2286500.00
         AND v.VAULT_CLOSING_USD = 16400000.00
         AND l.COMPLETED_LOAN_APPS = 2

        THEN TRUE

        ELSE FALSE

    END AS AUDIT_SANITY_FLAG

FROM WIRE_TOTAL w

CROSS JOIN LATEST_VAULT v

CROSS JOIN COMPLETED_LOANS l;


