 --TASK 4: ACCUMULATING SNAPSHOT FACT


CREATE OR REPLACE TABLE FACT_CREDIT_APPROVAL_LIFECYCLE
(
    APP_ID              VARCHAR(30),

    SUBMISSION_DATE     DATE,
    UNDERWRITE_DATE     DATE,
    RISK_APPROVAL_DATE  DATE,
    DISBURSEMENT_DATE   DATE,

    UNDERWRITE_DAYS     NUMBER,
    RISK_APPROVAL_DAYS  NUMBER,
    DISBURSEMENT_DAYS   NUMBER,
    TOTAL_CYCLE_DAYS    NUMBER
);

INSERT INTO FACT_CREDIT_APPROVAL_LIFECYCLE
(
    APP_ID,
    SUBMISSION_DATE,
    UNDERWRITE_DATE,
    RISK_APPROVAL_DATE,
    DISBURSEMENT_DATE,

    UNDERWRITE_DAYS,
    RISK_APPROVAL_DAYS,
    DISBURSEMENT_DAYS,
    TOTAL_CYCLE_DAYS
)
SELECT
    APP_ID,

    SUBMISSION_DATE,
    UNDERWRITE_DATE,
    RISK_APPROVAL_DATE,
    DISBURSEMENT_DATE,

    CASE
        WHEN UNDERWRITE_DATE IS NOT NULL
        THEN DATEDIFF(
            'DAY',
            SUBMISSION_DATE,
            UNDERWRITE_DATE
        )
    END AS UNDERWRITE_DAYS,

    CASE
        WHEN UNDERWRITE_DATE IS NOT NULL
         AND RISK_APPROVAL_DATE IS NOT NULL
        THEN DATEDIFF(
            'DAY',
            UNDERWRITE_DATE,
            RISK_APPROVAL_DATE
        )
    END AS RISK_APPROVAL_DAYS,

    CASE
        WHEN RISK_APPROVAL_DATE IS NOT NULL
         AND DISBURSEMENT_DATE IS NOT NULL
        THEN DATEDIFF(
            'DAY',
            RISK_APPROVAL_DATE,
            DISBURSEMENT_DATE
        )
    END AS DISBURSEMENT_DAYS,

    CASE
        WHEN DISBURSEMENT_DATE IS NOT NULL
        THEN DATEDIFF(
            'DAY',
            SUBMISSION_DATE,
            DISBURSEMENT_DATE
        )
    END AS TOTAL_CYCLE_DAYS

FROM RAW_CREDIT_LIFECYCLES;

-- VALIDATE TASK 4
SELECT
    APP_ID,
    SUBMISSION_DATE,
    UNDERWRITE_DATE,
    RISK_APPROVAL_DATE,
    DISBURSEMENT_DATE,
    UNDERWRITE_DAYS,
    RISK_APPROVAL_DAYS,
    DISBURSEMENT_DAYS,
    TOTAL_CYCLE_DAYS
FROM FACT_CREDIT_APPROVAL_LIFECYCLE
ORDER BY APP_ID;


 --TASK 5: IDENTIFY CURRENT BOTTLENECK


SELECT
    APP_ID,
    SUBMISSION_DATE,

    CASE

        WHEN DISBURSEMENT_DATE IS NULL
         AND RISK_APPROVAL_DATE IS NOT NULL
        THEN 'AWAITING_DISBURSAL'

        WHEN RISK_APPROVAL_DATE IS NULL
         AND UNDERWRITE_DATE IS NOT NULL
        THEN 'AWAITING_RISK_AUTH'

        WHEN UNDERWRITE_DATE IS NULL
        THEN 'AWAITING_UNDERWRITE'

        ELSE 'COMPLETED'

    END AS CURRENT_BOTTLENECK

FROM FACT_CREDIT_APPROVAL_LIFECYCLE

ORDER BY APP_ID;

