CREATE OR REPLACE TABLE DIM_WIRE_ATTRIBUTES
(
    ATTRIBUTE_SK      NUMBER PRIMARY KEY,
    AUTH_METHOD       VARCHAR(30),
    RISK_FLAG         VARCHAR(20),
    TRANSFER_TYPE     VARCHAR(30)
);

INSERT INTO DIM_WIRE_ATTRIBUTES
(
    ATTRIBUTE_SK,
    AUTH_METHOD,
    RISK_FLAG,
    TRANSFER_TYPE
)
SELECT
    ROW_NUMBER() OVER
    (
        ORDER BY
            AUTH_METHOD,
            RISK_FLAG,
            TRANSFER_TYPE
    ) AS ATTRIBUTE_SK,

    AUTH_METHOD,
    RISK_FLAG,
    TRANSFER_TYPE

FROM
(
    SELECT DISTINCT
        AUTH_METHOD,
        RISK_FLAG,
        TRANSFER_TYPE
    FROM RAW_WIRE_TRANSFERS
);


 --VALIDATE TASK 1
 
SELECT *
FROM DIM_WIRE_ATTRIBUTES
ORDER BY ATTRIBUTE_SK;


 --TASK 2: TRANSACTION FACT + DEGENERATE DIMENSION


CREATE OR REPLACE TABLE FACT_WIRE_TRANSFERS
(
    TXN_ID            VARCHAR(30),
    TXN_DATE          DATE,
    SENDER_ACC        VARCHAR(30),
    RECEIVER_ACC      VARCHAR(30),

    ATTRIBUTE_SK      NUMBER,

    AMOUNT            NUMBER(18,2),
    FEE               NUMBER(18,2),
    CURRENCY_RATE     NUMBER(10,4),

    BASE_AMOUNT_USD   NUMBER(18,2),
    NET_TRANSFER_VAL  NUMBER(18,2)
);

INSERT INTO FACT_WIRE_TRANSFERS
(
    TXN_ID,
    TXN_DATE,
    SENDER_ACC,
    RECEIVER_ACC,
    ATTRIBUTE_SK,
    AMOUNT,
    FEE,
    CURRENCY_RATE,
    BASE_AMOUNT_USD,
    NET_TRANSFER_VAL
)
SELECT
    r.TXN_ID,
    r.TXN_DATE,
    r.SENDER_ACC,
    r.RECEIVER_ACC,

    d.ATTRIBUTE_SK,

    r.AMOUNT,
    r.FEE,
    r.CURRENCY_RATE,

    ROUND(
        r.AMOUNT * r.CURRENCY_RATE,
        2
    ) AS BASE_AMOUNT_USD,

    ROUND(
        (r.AMOUNT * r.CURRENCY_RATE) - r.FEE,
        2
    ) AS NET_TRANSFER_VAL

FROM RAW_WIRE_TRANSFERS r

INNER JOIN DIM_WIRE_ATTRIBUTES d
    ON r.AUTH_METHOD = d.AUTH_METHOD
   AND r.RISK_FLAG = d.RISK_FLAG
   AND r.TRANSFER_TYPE = d.TRANSFER_TYPE;


 --VALIDATE TASK 2

SELECT
    TXN_ID,
    ATTRIBUTE_SK,
    AMOUNT,
    FEE,
    BASE_AMOUNT_USD,
    NET_TRANSFER_VAL
FROM FACT_WIRE_TRANSFERS
ORDER BY TXN_ID;



