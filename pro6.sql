---PHASE 6 — Business Reports
--Report 1 — Customer-wise Sales
SELECT
    c.CUSTOMER_ID,
    c.CUSTOMER_NAME,
    SUM(f.QUANTITY) AS TOTAL_QUANTITY,
    SUM(f.TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM FACT_SALES f
JOIN DIM_CUSTOMER c
    ON f.CUSTOMER_ID = c.CUSTOMER_ID
GROUP BY
    c.CUSTOMER_ID,
    c.CUSTOMER_NAME
ORDER BY TOTAL_REVENUE DESC;

--Report 2 — Product-wise Revenue
SELECT
    p.PRODUCT_ID,
    p.PRODUCT_NAME,
    SUM(f.QUANTITY) AS TOTAL_QUANTITY,
    SUM(f.TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM FACT_SALES f
JOIN DIM_PRODUCT p
    ON f.PRODUCT_ID = p.PRODUCT_ID
GROUP BY
    p.PRODUCT_ID,
    p.PRODUCT_NAME
ORDER BY TOTAL_REVENUE DESC;

--Report 3 — Brand-wise Revenue
SELECT
    b.BRAND_NAME,
    SUM(f.TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM FACT_SALES f
JOIN DIM_PRODUCT p
    ON f.PRODUCT_ID = p.PRODUCT_ID
JOIN DIM_BRAND b
    ON p.BRAND_ID = b.BRAND_ID
GROUP BY b.BRAND_NAME
ORDER BY TOTAL_REVENUE DESC;

--Report 4 — Category-wise Revenue
SELECT
    c.CATEGORY_NAME,
    SUM(f.TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM FACT_SALES f
JOIN DIM_PRODUCT p
    ON f.PRODUCT_ID = p.PRODUCT_ID
JOIN DIM_BRAND b
    ON p.BRAND_ID = b.BRAND_ID
JOIN DIM_CATEGORY c
    ON b.CATEGORY_ID = c.CATEGORY_ID
GROUP BY c.CATEGORY_NAME
ORDER BY TOTAL_REVENUE DESC;

--Report 5 — City-wise Sales
SELECT
    ci.CITY_NAME,
    SUM(f.TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM FACT_SALES f
JOIN DIM_CUSTOMER c
    ON f.CUSTOMER_ID = c.CUSTOMER_ID
JOIN DIM_CITY ci
    ON c.CITY_ID = ci.CITY_ID
GROUP BY ci.CITY_NAME
ORDER BY TOTAL_REVENUE DESC;

--Report 6 — State-wise Revenue
SELECT
    s.STATE_NAME,
    SUM(f.TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM FACT_SALES f
JOIN DIM_CUSTOMER c
    ON f.CUSTOMER_ID = c.CUSTOMER_ID
JOIN DIM_CITY ci
    ON c.CITY_ID = ci.CITY_ID
JOIN DIM_STATE s
    ON ci.STATE_ID = s.STATE_ID
GROUP BY s.STATE_NAME
ORDER BY TOTAL_REVENUE DESC;

--Report 7 — Region-wise Revenue
SELECT
    r.REGION_NAME,
    SUM(f.TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM FACT_SALES f
JOIN DIM_BRANCH b
    ON f.BRANCH_ID = b.BRANCH_ID
JOIN DIM_CITY ci
    ON b.CITY_ID = ci.CITY_ID
JOIN DIM_STATE s
    ON ci.STATE_ID = s.STATE_ID
JOIN DIM_REGION r
    ON s.REGION_ID = r.REGION_ID
GROUP BY r.REGION_NAME
ORDER BY TOTAL_REVENUE DESC;

--Report 8 — Monthly Revenue
SELECT
    y.YEAR_VALUE,
    q.QUARTER_NAME,
    m.MONTH_NAME,
    SUM(f.TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM FACT_SALES f
JOIN DIM_DATE d
    ON f.DATE_ID = d.DATE_ID
JOIN DIM_MONTH m
    ON d.MONTH_ID = m.MONTH_ID
JOIN DIM_QUARTER q
    ON m.QUARTER_ID = q.QUARTER_ID
JOIN DIM_YEAR y
    ON q.YEAR_ID = y.YEAR_ID
GROUP BY
    y.YEAR_VALUE,
    q.QUARTER_NAME,
    m.MONTH_NAME
ORDER BY
    y.YEAR_VALUE,
    m.MONTH_NAME;

