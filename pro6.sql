CREATE OR REPLACE TABLE DIM_QUARTER
(
    QUARTER_ID NUMBER PRIMARY KEY,
    QUARTER_NAME STRING,
    YEAR_ID NUMBER,

    CONSTRAINT FK_QUARTER_YEAR
        FOREIGN KEY (YEAR_ID)
        REFERENCES DIM_YEAR(YEAR_ID)
);

INSERT INTO DIM_QUARTER
(
    QUARTER_ID,
    QUARTER_NAME,
    YEAR_ID
)
SELECT DISTINCT
    c.YEAR * 10 +
    CAST(SUBSTR(c.QUARTER, 2) AS NUMBER) AS QUARTER_ID,

    c.QUARTER,

    y.YEAR_ID
FROM STG_CALENDAR c
JOIN DIM_YEAR y
    ON c.YEAR = y.YEAR_VALUE;


