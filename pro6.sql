CREATE OR REPLACE TABLE DIM_REGION
(
    REGION_ID NUMBER PRIMARY KEY,
    REGION_NAME STRING
);


INSERT INTO DIM_REGION
SELECT
    ROW_NUMBER() OVER (ORDER BY REGION) AS REGION_ID,
    REGION
FROM
(
    SELECT DISTINCT REGION
    FROM STG_BRANCHES
);

SELECT * FROM DIM_REGION
ORDER BY REGION_ID;

CREATE OR REPLACE TABLE DIM_STATE
(
    STATE_ID NUMBER PRIMARY KEY,
    STATE_NAME STRING,
    REGION_ID NUMBER,
    
    CONSTRAINT FK_STATE_REGION
        FOREIGN KEY (REGION_ID)
        REFERENCES DIM_REGION(REGION_ID)
);

INSERT INTO DIM_STATE
(
    STATE_ID,
    STATE_NAME,
    REGION_ID
)
SELECT
    ROW_NUMBER() OVER (ORDER BY STATE_NAME),
    STATE_NAME,
    REGION_ID
FROM
(
    SELECT
        STATE_NAME,
        MAX(REGION_ID) AS REGION_ID
    FROM
    (
        SELECT
            STATE AS STATE_NAME,
            r.REGION_ID
        FROM STG_BRANCHES b
        JOIN DIM_REGION r
            ON b.REGION = r.REGION_NAME

        UNION ALL

        SELECT
            STATE AS STATE_NAME,
            NULL AS REGION_ID
        FROM STG_CUSTOMERS
    )
    GROUP BY STATE_NAME
);

SELECT *
FROM DIM_STATE
ORDER BY STATE_ID;

CREATE OR REPLACE TABLE DIM_CITY
(
    CITY_ID NUMBER PRIMARY KEY,
    CITY_NAME STRING,
    STATE_ID NUMBER,

    CONSTRAINT FK_CITY_STATE
        FOREIGN KEY (STATE_ID)
        REFERENCES DIM_STATE(STATE_ID)
);

INSERT INTO DIM_CITY
(
    CITY_ID,
    CITY_NAME,
    STATE_ID
)
SELECT
    ROW_NUMBER() OVER (ORDER BY CITY_NAME),
    CITY_NAME,
    STATE_ID
FROM
(
    SELECT DISTINCT
        c.CITY AS CITY_NAME,
        s.STATE_ID
    FROM STG_CUSTOMERS c
    JOIN DIM_STATE s
        ON c.STATE = s.STATE_NAME

    UNION

    SELECT DISTINCT
        b.CITY AS CITY_NAME,
        s.STATE_ID
    FROM STG_BRANCHES b
    JOIN DIM_STATE s
        ON b.STATE = s.STATE_NAME
);

SELECT * FROM DIM_CITY
ORDER BY CITY_ID;


