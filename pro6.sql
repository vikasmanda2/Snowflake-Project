    SUM(f.TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM FACT_SALES f
JOIN DIM_BRANCH b
    ON f.BRANCH_ID = b.BRANCH_ID
GROUP BY
    b.BRANCH_ID,
    b.BRANCH_NAME
ORDER BY TOTAL_REVENUE DESC
LIMIT 10;

--Customer Purchase Trend
SELECT
    c.CUSTOMER_NAME,
    d.DATE,
    SUM(f.TOTAL_AMOUNT) AS DAILY_REVENUE
FROM FACT_SALES f
JOIN DIM_CUSTOMER c
    ON f.CUSTOMER_ID = c.CUSTOMER_ID
JOIN DIM_DATE d
    ON f.DATE_ID = d.DATE_ID
GROUP BY
    c.CUSTOMER_NAME,
    d.DATE
ORDER BY
    c.CUSTOMER_NAME,
    d.DATE;
--Product Performance Dashboard Query
SELECT
    p.PRODUCT_NAME,
    b.BRAND_NAME,
    c.CATEGORY_NAME,
    SUM(f.QUANTITY) AS TOTAL_UNITS_SOLD,
    SUM(f.TOTAL_AMOUNT) AS TOTAL_REVENUE,
    AVG(f.TOTAL_AMOUNT) AS AVG_SALE_AMOUNT
FROM FACT_SALES f
JOIN DIM_PRODUCT p
    ON f.PRODUCT_ID = p.PRODUCT_ID
JOIN DIM_BRAND b
    ON p.BRAND_ID = b.BRAND_ID
JOIN DIM_CATEGORY c
    ON b.CATEGORY_ID = c.CATEGORY_ID
GROUP BY
    p.PRODUCT_NAME,
    b.BRAND_NAME,
    c.CATEGORY_NAME
ORDER BY TOTAL_REVENUE DESC;
--Regional Sales Dashboard
SELECT
    r.REGION_NAME,
    s.STATE_NAME,
    ci.CITY_NAME,
    b.BRANCH_NAME,
    SUM(f.QUANTITY) AS TOTAL_UNITS,
    SUM(f.TOTAL_AMOUNT) AS TOTAL_REVENUE
FROM FACT_SALES f
JOIN DIM_BRANCH b
    ON f.BRANCH_ID = b.BRANCH_ID
JOIN DIM_CITY ci
    ON b.CITY_ID = ci.CITY_ID
JOIN DIM_STATE s
    ON ci.STATE_ID = s.STATE_ID
JOIN DIM_REGION r
    ON s.REGION_ID = r.REGION_ID
GROUP BY
    r.REGION_NAME,
    s.STATE_NAME,
    ci.CITY_NAME,
    b.BRANCH_NAME
ORDER BY TOTAL_REVENUE DESC;
